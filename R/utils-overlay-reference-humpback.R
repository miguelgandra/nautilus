.referenceHumpbackSpec <- function() {
  controls <- .referenceHumpbackControls();b <- controls$body;z <- (b[,3]+b[,4])/2
  body <- .anatomyBody(b[,1],b[,2],z-b[,3],b[,4]-z,z)
  foil <- function(id,section.id,sections,role) {
    p <- controls[[section.id]]
    out <- .anatomyFoil(id,cbind(p[,1:3],(p[,4]+p[,5])/2,p[,6]),role=role,sections=sections)
    out$leading[,3] <- p[,4];out$trailing[,3] <- p[,5]
    out$pivot <- (out$leading[1,]+out$trailing[1,])/2
    out$allocation <- "measured planform, droop and thickness; embedded root; finite tapered tip"
    out
  }
  pectoral <- foil("pectoral","pectoral",6L,"rigid")
  # Extrude thickness across the average measured chord plane, not vertically.
  # This keeps the narrow, tilted outer pectoral sections transverse as well.
  chord <- colSums(pectoral$leading-pectoral$trailing)
  pectoral$normal <- c(-chord[3]/chord[1],0,1)
  pectoral$normal <- pectoral$normal/sqrt(sum(pectoral$normal^2))
  fluke <- foil("fluke","fluke",4L,"terminal")
  dorsal <- .anatomyFoil("dorsal",controls$dorsal,"xz","attached",4L)
  dorsal$allocation <- "small measured aft dorsal above the back; embedded base"
  spec <- .anatomySpec("Humpback whale","Megaptera novaeangliae",2L,body,
    c(.anatomyPair(pectoral),list(dorsal),.anatomyPair(fluke)),
    c("reference-fitted broad rostrum and tapering trunk",
      "long swept and drooping pectorals following the neutral source pose",
      "small aft dorsal, continuous peduncle and broad notched horizontal flukes"),
    character(),type="vertical",sections=10L,pivot=c(0,0,0),tip=-37,
    landmarks=list(TL=100,body.width=2*max(b[,2]),body.depth=max(b[,4]-b[,3]),
      pectoral.origin=30,pectoral.span=38.16,pectoral.centreline.length=23.33,
      first.dorsal.origin=62.2,fluke.span=28.84,
      basis="neutral supplied GLB sections; paired fins mirrored; source sweep and droop retained"))
  spec$body.angles <- c(0,pi/4,pi/2,3*pi/4,pi,7*pi/6,4*pi/3,3*pi/2,5*pi/3,11*pi/6)
  rings <- controls$body_vertices
  order <- unlist(lapply(rev(seq_len(nrow(b))),function(i) (i-1L)*10L+seq_len(10L)))
  rings <- rings[order,,drop=FALSE]
  spec$body.transform <- function(vertices) {
    n <- nrow(rings);vertices[seq_len(n),] <- rings
    vertices[n+1L,] <- colMeans(rings[1:10,,drop=FALSE])
    vertices[n+2L,] <- colMeans(tail(rings,10))
    vertices
  }
  spec$appearance <- list(smooth=TRUE,smooth.faces=rep(TRUE,696L),cull=TRUE,
    fit="legacy",eye.cex=.65,compass=c(1.12,1.10,.18),dorsal="#35434d",ventral="#d8ddd8")
  spec$surface <- "humpback"
  spec$revision <- "humpback-surface-v18"
  spec$review <- list(status="approved",checkpoint="v18",date="2026-10-28",
    geometry=list(status="approved",checkpoint="v17",date="2026-10-28"),
    measured.views=c("dorsal","lateral","anterior"),
    interpretation="neutral asset proportions and swept drooping flippers; slight asymmetry made bilateral; tiny head bumps and tail scallops simplified")
  spec$anatomy <- "approved reference geometry; schematic vertical tail rig; UV-guided eyes and simplified source-inspired surface markings"
  spec
}
