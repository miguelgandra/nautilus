.referenceTurtleSpec <- function() {
  controls <- .referenceTurtleControls(); b <- controls$body
  body <- .anatomyBody(b[,1],b[,2],b[,5]-b[,3],b[,4]-b[,5],b[,5])
  foil <- function(id, sections, role) {
    p <- controls[[id]]
    out <- .anatomyFoil(id,cbind(p[,1:3],(p[,4]+p[,5])/2,p[,6]),role=role,sections=sections)
    out$leading[,3] <- p[,4];out$trailing[,3] <- p[,5]
    out$pivot <- (out$leading[1,]+out$trailing[1,])/2
    out$section.vertices <- controls[[if (id == "foreflipper") "fore_vertices" else "hind_vertices"]]
    out$allocation <- "intact-side measured planform and thickness; embedded shoulder; mirrored pair"
    out
  }
  fore <- foil("foreflipper",6L,"flipper")
  hind <- foil("hindflipper",4L,"rigid")
  h <- controls$head; z <- (h[,3]+h[,4])/2
  head <- list(id="head_neck",kind="loft",part="body",role="rigid",joint.x=NA_real_,sections=8L,
    pivot=c(29,0,-11),allocation="measured extended neck and blunt beak sections",
    stations=.anatomyBody(h[,1],h[,2],z-h[,3],h[,4]-z,z))
  plastron <- list(id="plastron",kind="loft",part="body",role="rigid",joint.x=NA_real_,sections=6L,
    pivot=c(0,0,0),allocation="shallow ventral shell insert",
    stations=.anatomyBody(c(30,50,70,89),c(12,21,20,10),rep(.5,4),rep(.4,4),c(-1,-.2,-.3,-2.5)))
  tail <- .speciesFinSpec("tail",rbind(c(-45,-1,-7),c(-50,0,-7),c(-45,1,-7)),
    thickness=.5,part="body")
  spec <- .anatomySpec("Green sea turtle","Chelonia mydas",1L,body,
    c(.anatomyPair(fore),.anatomyPair(hind),list(head,plastron,tail)),
    c("reference-fitted domed carapace and extended blunt head",
      "bilaterally reconstructed oar foreflippers and separate hind paddles",
      "shallow plastron and short tail; rigid shoulder-driven foreflippers"),
    character(),type="flippers",sections=10L,pivot=fore$pivot,tip=46.6,
    landmarks=list(TL=100,carapace.length=81.94,carapace.width=60.15,body.depth=26.9,
      head.length=21.44,pectoral.span=93.3,pectoral.origin=21,
      basis="neutral GLB intact-side sections mirrored; snout-to-tail TL excludes hind-flipper overhang"))
  spec$body.angles <- c(0,pi/8,pi/2,7*pi/8,pi,7*pi/6,4*pi/3,3*pi/2,5*pi/3,11*pi/6)
  # Loft topology runs tail-to-head. Replace its rings with measured shell
  # sections to retain the broad ventral rim instead of an elliptical belly.
  rings <- controls$body_vertices
  order <- unlist(lapply(rev(seq_len(nrow(b))),function(i) (i-1L)*10L+seq_len(10L)))
  rings <- rings[order,,drop=FALSE]
  spec$body.transform <- function(vertices) {
    n <- nrow(rings);vertices[seq_len(n),] <- rings
    vertices[n+1L,] <- colMeans(rings[1:10,,drop=FALSE])
    vertices[n+2L,] <- colMeans(tail(rings,10))
    vertices
  }
  spec$rig$flipper.mode <- "rigid"
  spec$rig$weighting <- "rigid synchronous foreflipper rotation about mirrored shoulder pivots"
  spec$appearance <- list(smooth=TRUE,smooth.faces=rep(TRUE,690L),cull=TRUE,fit="legacy",eye.cex=.85,
    compass=c(1.12,1.10,.18),dorsal="#68583b",ventral="#dfd5a4")
  spec$surface <- "turtle"
  spec$revision <- "turtle-surface-v16"
  spec$review <- list(status="approved",checkpoint="v16",date="2026-10-28",
    geometry=list(status="approved",checkpoint="v15",date="2026-10-28"),
    surface.basis="UV-guided shell seams and eye socket placement; schematic beak, plastron seams and flipper scale plates",
    measured.views=c("dorsal","lateral","anterior"),
    reconstruction="intact positive lateral half mirrored; other foreflipper lacks a comparable blade in stored and default poses")
  spec$anatomy <- "approved reference-fitted geometry; bilateral reconstruction; reference-guided shell appearance and schematic small details"
  spec
}
