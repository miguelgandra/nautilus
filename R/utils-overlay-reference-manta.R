.referenceMantaSpec <- function() {
  c <- .referenceMantaControls()
  body<-c$body;z<-(body[,3]+body[,4])/2
  body<-.anatomyBody(body[,1],body[,2],z-body[,3],body[,4]-z,z)
  w<-c$wing
  wing<-.anatomyFoil("wing",cbind(w[,1:3],(w[,4]+w[,5])/2,w[,6]),role="flipper",sections=6L)
  wing$section.vertices<-c$wing_vertices
  wing$leading<-c$wing_vertices[seq(1,nrow(c$wing_vertices),6),,drop=FALSE]
  wing$trailing<-c$wing_vertices[seq(4,nrow(c$wing_vertices),6),,drop=FALSE]
  wing$pivot<-c(22,5.5,1);wing$allocation<-"measured wing roots, planform, camber and free-tip taper"
  h<-c$cephalic[order(c$cephalic[,1],decreasing=TRUE),]
  mid<-(h[,4]+h[,5])/2
  horn<-list(id="cephalic_right",kind="loft",axis="x",part="body",role="rigid",joint.x=NA_real_,
    sections=6L,centreline=h[,2],pivot=c(50-h[1,1],h[1,2],mid[1]),
    allocation="measured inward-curving cephalic lobe",
    stations=.speciesBody(50-h[,1],h[,3],mid-h[,4],h[,5]-mid,mid))
  left<-horn;left$id<-"cephalic_left";left$centreline<- -left$centreline;left$pivot[2]<- -left$pivot[2]
  t<-c$tail[order(c$tail[,1],decreasing=TRUE),];mid<-(t[,3]+t[,4])/2
  tail<-list(id="tail",kind="loft",part="body",role="rigid",joint.x=NA_real_,sections=6L,
    pivot=c(5,0,tail(mid,1)),allocation="measured intact whip centreline and taper",
    stations=.speciesBody(50-t[,1],t[,2],pmax(.003,mid-t[,3]),pmax(.003,t[,4]-mid),mid))
  dorsal<-.anatomyFoil("dorsal",c$dorsal,"xz","rigid",4L)
  pelvic<-.anatomyFoil("pelvic",c$pelvic,"xy","rigid",4L)
  spec<-.anatomySpec("Manta ray","Mobula alfredi / Mobula birostris",1L,body,
    c(.anatomyPair(wing),list(horn,left,tail,dorsal),.anatomyPair(pelvic)),
    c("neutral reference-fitted disc with measured wing planforms and thickness",
      "inward-curving cephalic lobes; tapered intact whip and small dorsal",
      "separate wing, cephalic, pelvic, dorsal and tail components"),
    character(),type="flippers",sections=8L,pivot=wing$pivot,tip=max(w[,1]),
    landmarks=list(TL=100,disc.width=2*max(w[,1]),tail.length=55,
      basis="neutral supplied manta asset; paired sections averaged; approved v7 geometry"))
  spec$revision<-"manta-surface-v8"
  # Shared manta countershading, not an individual or species-specific pattern.
  spec$appearance<-list(smooth=TRUE,cull=TRUE,fit="legacy",eye.cex=.65,
    compass=c(1.12,1.10,.18),dorsal="#4a616b",ventral="#e4e7df")
  spec$surface<-"manta"
  spec$review<-list(status="approved",checkpoint="v8",date="2026-10-27",
    geometry=list(status="approved",checkpoint="v7",date="2026-10-27"))
  spec$anatomy<-"reference-fitted manta schematic; neutral pose, paired sections averaged"
  spec
}
